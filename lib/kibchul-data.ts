export function getSubjectById(id: number) {
  return KIBCHUL_SUBJECTS.find(s => s.id === id);
}
export function getSessionsBySubject(subjectId: number): KibchulSession[] {
  return getSubjectById(subjectId)?.sessions ?? [];
}
export function getQuestionsBySession(subjectId: number, sessionId: string): KibchulQuestion[] {
  return getSessionsBySubject(subjectId).find(s => s.id === sessionId)?.questions ?? [];
}
export function getTotalQuestionCount(subjectId: number): number {
  return getSessionsBySubject(subjectId).reduce((sum, s) => sum + s.questions.length, 0);
}
