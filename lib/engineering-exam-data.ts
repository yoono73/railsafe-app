// 영역별 통계
export function getPartStats() {
  const stats: Record<number, { total: number; gradeAp: number; gradeA: number }> = {};
  for (let p = 1; p <= 9; p++) {
    const qs = engineeringQuestions.filter(q => q.part === p);
    stats[p] = {
      total: qs.length,
      gradeAp: qs.filter(q => q.grade === 'A+').length,
      gradeA: qs.filter(q => q.grade === 'A').length,
    };
  }
  return stats;
}
